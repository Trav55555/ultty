#!/usr/bin/env bash
# Write docs/compat-scorecard.md from the workspace's `scorecard_` tests.
#
#   scripts/compat-scorecard.sh           # regenerate the page
#   scripts/compat-scorecard.sh --check   # fail if the page is out of date
#
# Each row names a test prefix. The row reads "Yes" while every test with
# that prefix passes, "Broken" when one fails, and "No" when there is none.
set -euo pipefail
cd "$(dirname "$0")/.."
page=docs/compat-scorecard.md

# slug | feature | what programs use it for | notes
rows=$(cat <<'EOF'
synchronized_output|Synchronized output (mode 2026)|Redrawing a whole screen without flicker: agent CLIs, editors|DECRQM reports it
kitty_keyboard|Kitty keyboard protocol|Shift+Enter for a new line in agent prompts; keys legacy encoding cannot tell apart|Flags 1, 2, 4, 8 and 16; query, push, pop
bracketed_paste|Bracketed paste (mode 2004)|Pasting a multi-line prompt without running it|ESC and C1 controls are removed from pasted text
focus_reporting|Focus reporting (mode 1004)|Pausing or redrawing when the window loses focus|
alternate_screen|Alternate screen (mode 1049)|Full-screen programs that restore the shell on exit|
sgr_mouse|SGR mouse (mode 1006)|Clicks and scrolling in TUIs, at any column|Also X10, 1005, 1015, 1007
grapheme_clusters|Grapheme clustering (mode 2027)|Emoji and combining text that line up with what the program expects|
true_colour_and_underline_styles|24-bit colour, underline styles and colour|Syntax highlighting, diagnostics squiggles|SGR 4:x, 58, 59
hyperlinks|Hyperlinks (OSC 8)|Clickable file paths and URLs in output|Ctrl+click opens http, https, mailto and ftp only
clipboard_write|Clipboard writes (OSC 52)|Copying from a program, including over ssh|Reads are refused; writes can be turned off
prompt_marks|Shell prompt marks (OSC 133)|Knowing where commands and their output start and end|Feeds `ulttyctl last-command` and command events
working_directory|Working directory (OSC 7)|Opening a new tab where the shell is|
notifications|Desktop notifications (OSC 9, OSC 777)|"Done" or "needs input" from a long-running agent|
progress|Progress (OSC 9;4)|A progress bar on the tab; ConEmu's sequence, also read by Windows Terminal and Ghostty|
colour_scheme_updates|Theme change reports (mode 2031)|Programs restyling when the system switches light/dark|
colour_queries|Colour queries (OSC 10, 11)|Choosing a light or dark palette at start|Reports the live theme
terminal_name|Terminal name (XTVERSION)|Detecting the terminal without guessing from TERM|
sixel|Sixel images|Inline images and plots|
kitty_graphics|Kitty graphics protocol|Inline images in programs that only speak kitty's protocol|Use Sixel
EOF
)

results=$(cargo test --workspace --no-fail-fast -- scorecard_ 2>&1 || true)
grep -q '^test result' <<<"$results" || { echo "$results" >&2; exit 1; }

status_of() {
    local tests
    tests=$(grep -E "^test ([a-z0-9_]+::)*scorecard_$1[a-z0-9_]* \.\.\. " <<<"$results" || true)
    if [ -z "$tests" ]; then
        echo "No"
    elif grep -qv ' ok$' <<<"$tests"; then
        echo "Broken"
    else
        echo "Yes"
    fi
}

render() {
    cat <<'EOF'
# Compatibility scorecard

What Ultty does for terminal features that modern programs, agent CLIs
especially, rely on. Generated by `scripts/compat-scorecard.sh` from the
`scorecard_` tests: a row says "Yes" only while its test passes. The checks
are in [`crates/ultty-vt/tests/scorecard.rs`](../crates/ultty-vt/tests/scorecard.rs)
and, for key encoding, `crates/ultty/src/keys.rs`. The README's
[ANSI Compatibility](../README.md#ansi-compatibility) section lists the rest.

| Feature | Ultty | What programs use it for | Notes |
|---|---|---|---|
EOF
    while IFS='|' read -r slug feature use notes; do
        printf '| %s | %s | %s | %s |\n' "$feature" "$(status_of "$slug")" "$use" "$notes"
    done <<<"$rows"
}

if [ "${1-}" = "--check" ]; then
    if ! diff -u "$page" <(render); then
        echo "$page is out of date: run scripts/compat-scorecard.sh" >&2
        exit 1
    fi
else
    render >"$page"
    echo "wrote $page"
fi
